/**
 * gen-force-mobile.mjs
 *
 * Generates src/styles/force-mobile.css from the app's existing mobile
 * `@media (max-width: Npx)` blocks (N <= 1000).
 *
 * Why: mobile browsers in "Desktop site" mode force a ~980px layout viewport
 * and ignore `width=device-width`, so the app's `max-width: 768px` styles
 * never apply and the phone sees a broken desktop layout. This script re-emits
 * every mobile media-query block scoped under `html.force-mobile`, so those
 * rules apply at ANY viewport width as soon as the detection script flags the
 * `<html>` element.
 *
 * Re-run after editing any mobile CSS:  node scripts/gen-force-mobile.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const stylesDir = join(here, "..", "src", "styles");

const FILES = [
  ["index.css", join(stylesDir, "..", "index.css")],
  ["dashboard.css", join(stylesDir, "dashboard.css")],
  ["dark-theme.css", join(stylesDir, "dark-theme.css")],
];
const MAX_WIDTH = 1000; // extract blocks with max-width <= 1000px

/* ---------- tiny CSS brace parser ---------- */

function matchBrace(str, openIdx) {
  let depth = 0;
  for (let i = openIdx; i < str.length; i++) {
    const c = str[i];
    if (c === "{") depth++;
    else if (c === "}") {
      depth--;
      if (depth === 0) return i;
    }
  }
  return str.length - 1;
}

function findMediaBlocks(css) {
  const blocks = [];
  const re = /@media\s*\(\s*max-width\s*:\s*(\d+)px\s*\)\s*\{/g;
  let m;
  while ((m = re.exec(css))) {
    const openIdx = m.index + m[0].length - 1; // position of "{"
    // strip comments so they can never leak into selector splitting
    const content = css
      .slice(openIdx + 1, matchBrace(css, openIdx))
      .replace(/\/\*[\s\S]*?\*\//g, "");
    blocks.push({ maxWidth: Number(m[1]), content });
  }
  return blocks;
}

/** Split top-level rules inside a block body. */
function parseRules(body) {
  const rules = [];
  let i = 0;
  const n = body.length;
  while (i < n) {
    while (i < n && /\s|;/.test(body[i])) i++;
    if (i >= n) break;

    if (body[i] === "@") {
      // at-rule: either a block (@media/@keyframes/@supports) or a statement
      const braceIdx = body.indexOf("{", i);
      if (braceIdx === -1) {
        const semiIdx = body.indexOf(";", i);
        rules.push({ atRule: true, selector: body.slice(i, semiIdx === -1 ? n : semiIdx), body: "" });
        i = semiIdx === -1 ? n : semiIdx + 1;
      } else {
        const closeIdx = matchBrace(body, braceIdx);
        rules.push({ atRule: true, selector: body.slice(i, braceIdx), body: body.slice(braceIdx + 1, closeIdx) });
        i = closeIdx + 1;
      }
      continue;
    }

    const braceIdx = body.indexOf("{", i);
    if (braceIdx === -1) break; // stray text — skip
    const closeIdx = matchBrace(body, braceIdx);
    rules.push({ selector: body.slice(i, braceIdx).trim(), body: body.slice(braceIdx + 1, closeIdx) });
    i = closeIdx + 1;
  }
  return rules;
}

/** Prefix every selector with `html.force-mobile ` (paren-aware comma split). */
function prefixSelector(sel) {
  const parts = [];
  let depth = 0;
  let cur = "";
  for (const ch of sel) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) {
      parts.push(cur.trim());
      cur = "";
    } else {
      cur += ch;
    }
  }
  if (cur.trim()) parts.push(cur.trim());

  return parts
    .map((p) => {
      if (p === "html") return "html.force-mobile";
      if (p.startsWith("html")) return p.replace(/^html/, "html.force-mobile");
      if (p === "body") return "html.force-mobile body";
      if (p === "#root") return "html.force-mobile #root";
      return "html.force-mobile " + p;
    })
    .join(",\n  ");
}

function emitRules(rules, out, file) {
  for (const rule of rules) {
    if (rule.atRule) {
      const sel = rule.selector;
      if (/^@media\s*\(/.test(sel)) {
        // nested media (e.g. the 400px block inside the 768px block): hoist,
        // because at a wide viewport its own width query would never fire.
        out.push(`  /* ${file}: nested ${sel.trim()} (hoisted) */`);
        emitRules(parseRules(rule.body), out, file);
        continue;
      }
      // @keyframes / @supports etc. — keep global, no scoping needed
      out.push(`  ${sel.trim()} {`);
      out.push(`    ${rule.body.trim()}`);
      out.push(`  }`);
      continue;
    }
    const prefixed = prefixSelector(rule.selector);
    out.push(`  ${prefixed} {`);
    out.push(`    ${rule.body.trim()}`);
    out.push(`  }`);
  }
}

/* ---------- build ---------- */

const header = `/* AUTO-GENERATED — do not edit by hand.
   Generated by scripts/gen-force-mobile.mjs (node scripts/gen-force-mobile.mjs).
   Re-emits the app's mobile @media (max-width: <=${MAX_WIDTH}px) blocks scoped
   under html.force-mobile so the mobile layout also applies when a mobile
   browser is in "Desktop site" mode (layout viewport forced to ~980px).
   Real desktop / normal mobile are untouched — the class is only added by the
   detection script in index.html. */

/* --- Foundation: make CSS px == physical px on the phone ---
   - zoom cancels the browser's fit-to-screen scale (innerWidth/screen.width)
   - the app container is constrained to the physical screen width.
   Net scale is 1:1, so everything must live in the CSS window [0, screen.width];
   the app column is left-aligned (margin: 0 — auto would push it to CSS ~310,
   i.e. off-screen). */
html.force-mobile {
  zoom: var(--fm-k, 2.7);
}

html.force-mobile body,
html.force-mobile #root {
  width: calc(var(--fm-w, 360) * 1px);
  max-width: none;
  overflow-x: hidden;
}

html.force-mobile body {
  margin: 0;
}
`;

const extra = `/* --- Force-mobile fixes that can't come from media blocks ---
   Viewport-centered fixed overlays center at CSS x=490 of the ~980px layout
   viewport, which lands off-screen at net scale 1:1. Constrain them to the
   app column (CSS [0, screen.width]) so modals stay centered on the phone. */
html.force-mobile .settings-modal-overlay,
html.force-mobile .escrow-modal-overlay {
  left: 0;
  right: auto;
  width: calc(var(--fm-w, 360) * 1px);
  justify-content: center;
}
`;

const out = [header];

for (const [file, path] of FILES) {
  const css = readFileSync(path, "utf8");
  const blocks = findMediaBlocks(css).filter((b) => b.maxWidth <= MAX_WIDTH);
  for (const block of blocks) {
    out.push(`/* ===== ${file} — @media (max-width: ${block.maxWidth}px) ===== */`);
    emitRules(parseRules(block.content), out, file);
    out.push(``);
  }
}

out.push(extra);

writeFileSync(join(stylesDir, "force-mobile.css"), out.join("\n"), "utf8");
console.log(`wrote force-mobile.css (${out.length} lines)`);
